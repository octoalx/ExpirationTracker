function generateBarcode(index: number): string {
  return `460${String(index + 1).padStart(7, "0")}`;
}

function randomDate(): Date {
  const now = new Date();
  const days = Math.floor(Math.random() * 365) - 30; // от -30 до +335 дней
  const date = new Date(now);
  date.setDate(date.getDate() + days);
  return date;
}

async function seed() {
  // Найти первого пользователя
  const user = await prisma.user.findFirst();
  if (!user) {
    console.error("No user found. Create a user first.");
    process.exit(1);
  }

  console.log(`Seeding 100 construction products for user ${user.id}...`);

  const products = constructionProducts.map((name, index) => ({
    name,
    barcode: generateBarcode(index),
    expiryDate: randomDate(),
    status: Math.random() > 0.8 ? "ARCHIVED" : "ACTIVE",
    isExpired: false,
    quantity: Math.random() > 0.3 ? Math.floor(Math.random() * 100) + 1 : null,
    userId: user.id,
  }));

  // Удалить существующие товары пользователя перед seed
  await prisma.product.deleteMany({
    where: { userId: user.id }
  });

  await prisma.product.createMany({
    data: products,
  });

  console.log(`✅ Created ${products.length} construction products`);
}

seed()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
